pub use super::data_clipboard::*;
use super::native;
use crate::error::{AppError, AppResult};
use base64::Engine;
use serde::Deserialize;
use serde_json::json;

const READ: &str = r#"
const p=$.NSPasteboard.generalPasteboard, sequence=Number(p.changeCount);
const types=ObjC.deepUnwrap(p.types)||[];
const concealed=types.some(t => ['org.nspasteboard.ConcealedType','org.nspasteboard.TransientType','org.nspasteboard.AutoGeneratedType','com.agilebits.onepassword'].includes(t));
if(concealed) return {sequence:sequence,private:true,files:[],text:null,png:null};
const value=p.stringForType($.NSPasteboardTypeString);
const text=value.isNil() ? null : ObjC.unwrap(value);
const urls=p.readObjectsForClassesOptions($.NSArray.arrayWithObject($.NSURL), $({NSPasteboardURLReadingFileURLsOnlyKey:true}));
const files=[];
if(urls && !urls.isNil()) for(let i=0;i<urls.count;i++) {
    const url=urls.objectAtIndex(i); if(url.isFileURL) files.push(ObjC.unwrap(url.path));
}
let png=null;
if(a.image) {
    let data=p.dataForType($.NSPasteboardTypePNG);
    if(!data || data.isNil()) {
        const tiff=p.dataForType($.NSPasteboardTypeTIFF);
        if(tiff && !tiff.isNil() && tiff.length <= 16*1024*1024) {
            const rep=$.NSBitmapImageRep.imageRepWithData(tiff);
            if(rep && !rep.isNil()) data=rep.representationUsingTypeProperties($.NSPNGFileType,$({}));
        }
    }
    if(data && !data.isNil()) {
        if(data.length > 16*1024*1024) throw Error('Изображение в буфере обмена слишком большое');
        png=ObjC.unwrap(data.base64EncodedStringWithOptions(0));
    }
}
if(Number(p.changeCount)!==sequence) throw Error('Буфер обмена изменился во время чтения');
return {sequence:sequence,private:false,files:files,text:text,png:png};
"#;
const WRITE: &str = r#"
const p=$.NSPasteboard.generalPasteboard;
let data=null, urls=null;
if(a.kind==='image') {
    data=$.NSData.alloc.initWithBase64EncodedStringOptions(a.png,0);
    if(!data || data.isNil()) throw Error('Некорректное изображение PNG');
}
if(a.kind==='files') {
    urls=$.NSMutableArray.alloc.init;
    for(const path of a.paths) urls.addObject($.NSURL.fileURLWithPath(path));
}
p.clearContents;
let ok=true;
if(a.kind==='text') ok=p.setStringForType(a.text,$.NSPasteboardTypeString);
if(a.kind==='image') ok=p.setDataForType(data,$.NSPasteboardTypePNG);
if(a.kind==='files') ok=p.writeObjects(urls);
if(!ok) throw Error('Не удалось записать буфер обмена macOS');
return true;
"#;
#[derive(Deserialize)]
struct Payload {
    sequence: u32,
    private: bool,
    files: Vec<String>,
    text: Option<String>,
    png: Option<String>,
}
fn parse(value: serde_json::Value) -> AppResult<Snapshot> {
    let p: Payload = serde_json::from_value(value)
        .map_err(|_| AppError::platform("Некорректный ответ буфера обмена macOS"))?;
    if p.private {
        return Ok(Snapshot {
            sequence: p.sequence,
            private: true,
            ..Default::default()
        });
    }
    let png = p
        .png
        .map(|s| {
            base64::engine::general_purpose::STANDARD
                .decode(s)
                .map_err(|_| AppError::platform("Некорректный PNG в буфере обмена"))
        })
        .transpose()?;
    Ok(Snapshot {
        sequence: p.sequence,
        owner_pid: None,
        private: false,
        text: p.text,
        files: p.files,
        png,
        dib: None,
    })
}
pub(super) fn change_count() -> AppResult<u32> {
    native::jxa(
        "return Number($.NSPasteboard.generalPasteboard.changeCount);",
        json!(null),
    )?
    .as_u64()
    .map(|n| n as u32)
    .ok_or_else(|| AppError::platform("Не удалось прочитать номер буфера обмена"))
}
pub fn read() -> AppResult<ClipboardContent> {
    let s = parse(native::jxa(READ, json!({"image":false}))?)?;
    Ok(ClipboardContent {
        text: s.text,
        files: s.files,
    })
}
pub fn snapshot() -> AppResult<Snapshot> {
    parse(native::jxa(READ, json!({"image":true}))?)
}
pub fn write_text(text: &str) -> AppResult<()> {
    native::jxa(WRITE, json!({"kind":"text","text":text}))?;
    Ok(())
}
pub fn write_image(png: &[u8], _dib: &[u8]) -> AppResult<()> {
    if png.len() > 16 * 1024 * 1024 {
        return Err(AppError::invalid(
            "Изображение для буфера обмена слишком большое",
        ));
    }
    image::load_from_memory_with_format(png, image::ImageFormat::Png)
        .map_err(|_| AppError::invalid("Некорректное изображение PNG"))?;
    native::jxa(
        WRITE,
        json!({"kind":"image","png":base64::engine::general_purpose::STANDARD.encode(png)}),
    )?;
    Ok(())
}
pub fn write_files(paths: &[String]) -> AppResult<()> {
    if paths.is_empty() {
        return Err(AppError::invalid("Не указаны файлы для копирования"));
    }
    let paths: Vec<String> = paths
        .iter()
        .map(|p| {
            std::fs::canonicalize(p)
                .map(|p| p.to_string_lossy().into_owned())
                .map_err(|_| AppError::not_found(format!("Файл не найден: {p}")))
        })
        .collect::<AppResult<_>>()?;
    native::jxa(WRITE, json!({"kind":"files","paths":paths}))?;
    Ok(())
}
pub fn restore(prev: &ClipboardContent) -> AppResult<()> {
    if !prev.files.is_empty() {
        write_files(&prev.files)
    } else if let Some(text) = &prev.text {
        write_text(text)
    } else {
        native::jxa(WRITE, json!({"kind":"clear"}))?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn parses_text_files_images_empty_and_private_payloads() {
        let p = parse(
            json!({"sequence":7,"private":false,"files":["/тест.txt"],"text":"текст","png":"aGk="}),
        )
        .unwrap();
        assert_eq!(p.sequence, 7);
        assert_eq!(p.text.as_deref(), Some("текст"));
        assert_eq!(p.png.unwrap(), b"hi");
        let p = parse(
            json!({"sequence":8,"private":true,"files":["secret"],"text":"secret","png":"bad"}),
        )
        .unwrap();
        assert!(p.private && p.text.is_none() && p.files.is_empty() && p.png.is_none());
        assert!(
            parse(json!({"sequence":0,"private":false,"files":[],"text":null,"png":null}))
                .unwrap()
                .text
                .is_none()
        );
        assert!(parse(json!({})).is_err());
        assert!(
            parse(json!({"sequence":0,"private":false,"files":[],"text":null,"png":"!"})).is_err()
        );
    }
}
